#!/usr/bin/env python3
"""Generate a minimal, pinned GitHub Actions workflow for a Nagi project."""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from pathlib import Path


VERSION_RE = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+", re.ASCII)
BUILD_PROFILE_VERSION = (0, 2, 1)
TOOLCHAIN_RE = re.compile(
    r"(?:stable|beta|nightly|[0-9]+\.[0-9]+(?:\.[0-9]+)?)(?:-[A-Za-z0-9_]+(?:-[A-Za-z0-9_]+)*)?",
    re.ASCII,
)


def validate_version(value: str) -> str:
    if VERSION_RE.fullmatch(value) is None:
        raise argparse.ArgumentTypeError("Nagi version must be a full X.Y.Z version")
    return value


def validate_toolchain(value: str) -> str:
    if TOOLCHAIN_RE.fullmatch(value) is None:
        raise argparse.ArgumentTypeError(
            "Rust toolchain must be stable, beta, nightly, or a numeric version"
        )
    return value


def validate_branch(value: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/-]*", value, re.ASCII) is None or ".." in value:
        raise argparse.ArgumentTypeError("default branch must be a literal branch name")
    return value


def version_tuple(value: str) -> tuple[int, int, int]:
    major, minor, patch = value.split(".")
    return int(major), int(minor), int(patch)


def workflow_text(
    version: str,
    toolchain: str,
    os_matrix: bool,
    branch: str = "main",
    build_profile: str = "release",
) -> str:
    if build_profile not in {"release", "dev"}:
        raise ValueError("build profile must be release or dev")
    if build_profile == "dev" and version_tuple(version) < BUILD_PROFILE_VERSION:
        raise ValueError("Development profile requires Nagi 0.2.1 or newer")

    supports_build_profile = version_tuple(version) >= BUILD_PROFILE_VERSION
    build_command = (
        f"nagic build --profile {build_profile}" if supports_build_profile else "nagic build"
    )
    build_step = f"""      - name: Build Nagi project on Unix
        if: runner.os != 'Windows'
        shell: bash
        run: |
          started="$(date +%s)"
          set +e
          {build_command}
          status=$?
          set -e
          elapsed="$(( $(date +%s) - started ))"
          printf 'Nagi build completed in %s seconds (exit code %s).\\n' "$elapsed" "$status" >> "$GITHUB_STEP_SUMMARY"
          exit "$status"
      - name: Build Nagi project on Windows
        if: runner.os == 'Windows'
        shell: pwsh
        run: |
          $started = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
          {build_command}
          $status = $LASTEXITCODE
          $elapsed = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds() - $started
          Add-Content -LiteralPath $env:GITHUB_STEP_SUMMARY -Value "Nagi build completed in $elapsed seconds (exit code $status)."
          exit $status
"""

    # Keep the Unix step off Windows so PowerShell preserves native exit codes
    # and writes the step summary with its native path handling.
    if os_matrix:
        build_runner = """    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, macos-latest, windows-latest]
    runs-on: ${{ matrix.os }}"""
    else:
        build_runner = "    runs-on: ubuntu-latest"

    return f"""# Generated by scripts/generate_project_ci.py.
# GitHub base-branch caches can be read by fork PRs: cache only public-safe data.
# Add application-specific test steps after the build; Nagi has no universal test command.
name: Nagi project CI

on:
  push:
    branches: ['{branch}']
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: nagi-project-${{{{ github.event.pull_request.number || github.ref }}}}
  cancel-in-progress: true

jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
        with:
          persist-credentials: false
      - name: Install Nagi {version}
        shell: bash
        run: |
          set -euo pipefail
          curl -fsSL https://raw.githubusercontent.com/disnana/Nagi/nagi-v{version}/scripts/install.sh | bash -s -- --version {version} --no-path
          printf '%s\\n' "$HOME/.local/bin" >> "$GITHUB_PATH"
      - name: Check Nagi project
        shell: bash
        run: |
          started="$(date +%s)"
          set +e
          nagic check
          status=$?
          set -e
          elapsed="$(( $(date +%s) - started ))"
          printf 'Nagi check completed in %s seconds (exit code %s).\\n' "$elapsed" "$status" >> "$GITHUB_STEP_SUMMARY"
          exit "$status"

  build:
    needs: check
{build_runner}
    env:
      NAGI_NATIVE_TARGET_DIR: ${{{{ github.workspace }}}}/native-target
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
        with:
          persist-credentials: false
      - id: rust
        uses: dtolnay/rust-toolchain@683b588c487a69d01f6c6ddf40f036ff682cc2c8
        with:
          toolchain: '{toolchain}'
      - name: Restore Cargo and Nagi native target cache
        id: cargo-cache
        uses: actions/cache/restore@0057852bfaa89a56745cba8c7296529d2fc39830 # v4
        with:
          path: |
            ~/.cargo/registry
            ~/.cargo/git
            native-target
            build/*/Cargo.lock
          key: nagi-project-v2-{version}-{build_profile}-${{{{ runner.os }}}}-${{{{ runner.arch }}}}-{toolchain}-${{{{ steps.rust.outputs.cachekey }}}}-${{{{ hashFiles('**/Cargo.lock', '**/Cargo.toml', 'nagi.toml') }}}}
      - name: Install Nagi {version} (Unix)
        if: runner.os != 'Windows'
        shell: bash
        run: |
          set -euo pipefail
          curl -fsSL https://raw.githubusercontent.com/disnana/Nagi/nagi-v{version}/scripts/install.sh | bash -s -- --version {version} --no-path
          printf '%s\\n' "$HOME/.local/bin" >> "$GITHUB_PATH"
      - name: Install Nagi {version} (Windows)
        if: runner.os == 'Windows'
        shell: pwsh
        run: |
          $script = Join-Path $env:RUNNER_TEMP 'nagi-install.ps1'
          Invoke-WebRequest -Uri 'https://raw.githubusercontent.com/disnana/Nagi/nagi-v{version}/scripts/install.ps1' -OutFile $script
          & $script -Version '{version}' -NoPath
          $nagiBin = Join-Path $env:LOCALAPPDATA 'Nagi\\versions\\current'
          Add-Content -LiteralPath $env:GITHUB_PATH -Value $nagiBin
{build_step.rstrip()}
      - name: Save Cargo cache from the default branch
        if: >-
          success() && github.event_name == 'push' &&
          github.ref == format('refs/heads/{{0}}', github.event.repository.default_branch)
        uses: actions/cache/save@0057852bfaa89a56745cba8c7296529d2fc39830 # v4
        with:
          path: |
            ~/.cargo/registry
            ~/.cargo/git
            native-target
            build/*/Cargo.lock
          key: ${{{{ steps.cargo-cache.outputs.cache-primary-key }}}}
"""


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate a GitHub Actions workflow for a Nagi user project."
    )
    parser.add_argument(
        "--nagi-version",
        type=validate_version,
        default="0.2.1",
        help="released Nagi version to install (default: 0.2.1)",
    )
    parser.add_argument(
        "--build-profile",
        choices=("release", "dev"),
        default="release",
        help="Nagi build profile (default: release; dev requires Nagi 0.2.1 or newer)",
    )
    parser.add_argument(
        "--toolchain",
        type=validate_toolchain,
        default="stable",
        help="Rust toolchain used for app builds (default: stable)",
    )
    parser.add_argument(
        "--default-branch", type=validate_branch, default="main",
        help="default branch receiving push builds (default: main)",
    )
    parser.add_argument(
        "--os-matrix",
        action="store_true",
        help="build on Ubuntu, macOS, and Windows instead of Ubuntu only",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="write the workflow to this path instead of stdout",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace an existing --output file",
    )
    return parser


def write_output(path: Path, content: str, force: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not force:
        with path.open("x", encoding="utf-8", newline="\n") as output:
            output.write(content)
        return

    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            prefix=f".{path.name}.",
            suffix=".tmp",
            dir=path.parent,
            delete=False,
        ) as output:
            temporary_path = Path(output.name)
            output.write(content)
        os.replace(temporary_path, path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.force and args.output is None:
        parser.error("--force requires --output")
    if args.build_profile == "dev" and version_tuple(args.nagi_version) < BUILD_PROFILE_VERSION:
        parser.error("--build-profile dev requires Nagi 0.2.1 or newer")

    content = workflow_text(
        args.nagi_version, args.toolchain, args.os_matrix, args.default_branch, args.build_profile
    )
    if args.output is None:
        sys.stdout.write(content)
        return 0
    try:
        write_output(args.output, content, args.force)
    except FileExistsError:
        parser.error(f"refusing to overwrite {args.output}; pass --force to replace it")
    except OSError as error:
        parser.error(f"could not write {args.output}: {error}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
