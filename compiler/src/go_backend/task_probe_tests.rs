use super::{function_name, go_output, source, Staging, NEXT_GENERATION};
use crate::{check, emit, parser, project::BuildProfile, source::SourceProvenance};
use std::{fs, io, path::PathBuf, sync::atomic::Ordering};

const HIGH: &str = r#"async def child(mode: i64) -> Result[i64, i64]:
    if mode == 2:
        assert_true(False)
    if mode == 1:
        return fail(22)
    return ok(17)

async def main():
    result = await child(0)
"#;

fn probe_directory() -> Staging {
    loop {
        let id = NEXT_GENERATION.fetch_add(1, Ordering::Relaxed);
        let path =
            std::env::temp_dir().join(format!("nagi-generated-task-{}-{id}", std::process::id()));
        match fs::create_dir(&path) {
            Ok(()) => {
                return Staging {
                    path,
                    published: false,
                }
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(error) => panic!("cannot reserve generated Go test directory: {error}"),
        }
    }
}

// This bridge is emitted only by the Rust test. The public emitter generates
// the checked child, its Future and the Result/Error representations.
fn task_probe_bridge() -> String {
    let child = function_name("child");
    format!(
        r#"// Test-only Go Task projection generated by nagic's Rust tests.
package main

import (
    "context"
    "nagi.internal/go-runtime/internal/taskscope"
)

{runtime}
type probeTaskFailure = nagiTaskFailure
const probePanicked = nagiTaskPanicked
const probeInternal = nagiTaskInternal
type probeReceived = nagiResult[nagiResult[int64, int64], probeTaskFailure]

func taskProbeReceive(scope *taskscope.Scope, mode int64, cleanup func()) probeReceived {{
    return nagiTaskReceive(scope, nagiTaskSpawn(scope, {child}(mode), cleanup))
}}

func taskProbeFinish(scope *taskscope.Scope) nagiResult[nagiUnit, nagiError] {{
    return nagiTaskFinish(scope)
}}

"#,
        runtime = super::task_lowering::RUNTIME,
    )
}

#[test]
#[ignore = "requires the external Go toolchain used by the backend integration tests"]
fn generated_single_child_task_projects_panic_and_preserves_business_result() {
    let mut high = parser::parse(HIGH, true).unwrap();
    check::check(&mut high).unwrap();
    let low = emit::low(&high);
    let checked = check::finalize(
        parser::parse(&low, false).unwrap(),
        Default::default(),
        SourceProvenance::user_low_unmapped(),
    )
    .unwrap();
    let generated = source(&checked, &[], BuildProfile::Dev).unwrap();
    let staging = probe_directory();
    let kernel = staging.path.join("internal/taskscope");
    fs::create_dir_all(&kernel).unwrap();
    fs::write(
        staging.path.join("go.mod"),
        include_str!("../../go-runtime/go.mod"),
    )
    .unwrap();
    fs::write(
        kernel.join("taskscope.go"),
        include_str!("../../go-runtime/internal/taskscope/taskscope.go"),
    )
    .unwrap();
    fs::write(staging.path.join("main.go"), &generated).unwrap();
    fs::write(staging.path.join("task_probe.go"), task_probe_bridge()).unwrap();
    fs::write(
        staging.path.join("task_probe_test.go"),
        include_str!("task_probe_test.go"),
    )
    .unwrap();

    if let Some(path) = std::env::var_os("NAGI_TEST_ARTIFACT_DIR") {
        let path = PathBuf::from(path);
        fs::create_dir_all(path.join("internal/taskscope")).unwrap();
        fs::write(path.join("task-probe.nagi"), HIGH).unwrap();
        fs::write(path.join("task-probe.low"), low).unwrap();
        for file in [
            "main.go",
            "task_probe.go",
            "task_probe_test.go",
            "go.mod",
            "internal/taskscope/taskscope.go",
        ] {
            fs::copy(staging.path.join(file), path.join(file)).unwrap();
        }
    }
    let output = go_output(
        &["test", "-count=1", "-timeout=20s", "-v", "."],
        &staging.path,
    )
    .unwrap();
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(output.status.success(), "{stdout}\n{stderr}");
    for case in ["value", "business_error", "panic"] {
        assert!(
            stdout.contains(&format!("--- PASS: TestGeneratedTaskProbe/{case} ")),
            "{stdout}"
        );
    }
    println!("{stdout}");
}

