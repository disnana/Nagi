use super::{function_name, go_output, source, Staging, NEXT_GENERATION};
use crate::{check, emit, parser, project::BuildProfile, source::SourceProvenance};
use std::{fs, io, path::PathBuf, sync::atomic::Ordering};

const HIGH: &str = r#"async def child(mode: i64) -> Result[i64, i64]:
    if mode == 2:
        assert_true(False)
    if mode == 1:
        return fail(22)
    return ok(17)

async def main():
    result = await child(0)
"#;

fn probe_directory() -> Staging {
    loop {
        let id = NEXT_GENERATION.fetch_add(1, Ordering::Relaxed);
        let path =
            std::env::temp_dir().join(format!("nagi-generated-task-{}-{id}", std::process::id()));
        match fs::create_dir(&path) {
            Ok(()) => {
                return Staging {
                    path,
                    published: false,
                }
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(error) => panic!("cannot reserve generated Go test directory: {error}"),
        }
    }
}

// This bridge is emitted only by the Rust test. The public emitter generates
// the checked child, its Future and the Result/Error representations.
fn task_probe_bridge() -> String {
    let child = function_name("child");
    format!(
        r#"// Test-only Go Task projection generated by nagic's Rust tests.
package main

import (
    "context"
    "nagi.internal/go-runtime/internal/taskscope"
)

{runtime}
type probeTaskFailure = nagiTaskFailure
const probePanicked = nagiTaskPanicked
const probeInternal = nagiTaskInternal
type probeReceived = nagiResult[nagiResult[int64, int64], probeTaskFailure]

func taskProbeReceive(scope *taskscope.Scope, mode int64, cleanup func()) probeReceived {{
    return nagiTaskReceive(scope, nagiTaskSpawn(scope, {child}(mode), cleanup))
}}

func taskProbeFinish(scope *taskscope.Scope) nagiResult[nagiUnit, nagiError] {{
    return nagiTaskFinish(scope)
}}

"#,
        runtime = super::task_lowering::RUNTIME,
    )
}

#[test]
#[ignore = "requires the external Go toolchain used by the backend integration tests"]
fn generated_single_child_task_projects_panic_and_preserves_business_result() {
    let mut high = parser::parse(HIGH, true).unwrap();
    check::check(&mut high).unwrap();
    let low = emit::low(&high);
    let checked = check::finalize(
        parser::parse(&low, false).unwrap(),
        Default::default(),
        SourceProvenance::user_low_unmapped(),
    )
    .unwrap();
    let generated = source(&checked, &[], BuildProfile::Dev).unwrap();
    let staging = probe_directory();
    let kernel = staging.path.join("internal/taskscope");
    fs::create_dir_all(&kernel).unwrap();
    fs::write(
        staging.path.join("go.mod"),
        include_str!("../../go-runtime/go.mod"),
    )
    .unwrap();
    fs::write(
        kernel.join("taskscope.go"),
        include_str!("../../go-runtime/internal/taskscope/taskscope.go"),
    )
    .unwrap();
    fs::write(staging.path.join("main.go"), &generated).unwrap();
    fs::write(staging.path.join("task_probe.go"), task_probe_bridge()).unwrap();
    fs::write(
        staging.path.join("task_probe_test.go"),
        include_str!("task_probe_test.go"),
    )
    .unwrap();

    if let Some(path) = std::env::var_os("NAGI_TEST_ARTIFACT_DIR") {
        let path = PathBuf::from(path);
        fs::create_dir_all(path.join("internal/taskscope")).unwrap();
        fs::write(path.join("task-probe.nagi"), HIGH).unwrap();
        fs::write(path.join("task-probe.low"), low).unwrap();
        for file in [
            "main.go",
            "task_probe.go",
            "task_probe_test.go",
            "go.mod",
            "internal/taskscope/taskscope.go",
        ] {
            fs::copy(staging.path.join(file), path.join(file)).unwrap();
        }
    }
    let output = go_output(
        &["test", "-count=1", "-timeout=20s", "-v", "."],
        &staging.path,
    )
    .unwrap();
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(output.status.success(), "{stdout}\n{stderr}");
    for case in ["value", "business_error", "panic"] {
        assert!(
            stdout.contains(&format!("--- PASS: TestGeneratedTaskProbe/{case} ")),
            "{stdout}"
        );
    }
    println!("{stdout}");
}

#[test]
#[ignore = "requires the external Go toolchain used by the backend integration tests"]
fn checked_single_task_lowers_scope_spawn_and_await_internally() {
    let panic_child = "    assert_true(False)\n    return ok(17)\n";
    let receive = "        received = await handle\n";
    let body_error = "        ignored: i64 = try error(\"body sentinel\")\n";
    for (mode, child) in [
        ("value", "    return ok(17)\n"),
        ("business_error", "    return fail(22)\n"),
        ("panic", panic_child),
        ("body_error_before_await", panic_child),
        ("body_error_after_await", panic_child),
        ("body_assert_true", "    return ok(17)\n"),
        ("body_assert_false", "    return ok(17)\n"),
        ("sleep_value", "    await sleep(0)\n    return ok(17)\n"),
        (
            "sleep_business_error",
            "    await sleep(0)\n    return fail(22)\n",
        ),
        (
            "sleep_body_panic",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "sleep_body_error",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_wait_normal",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        (
            "parent_cancel",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_receive_pending",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_receive_ready_cancel",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        (
            "parent_receive_value",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        (
            "parent_finish_pending",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_finish_deadline",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_finish_connection",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_finish_ready_cancel",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        (
            "parent_finish_normal",
            "    await sleep(0)\n    return fail(22)\n",
        ),
        (
            "parent_permit_cancel",
            "    await sleep(86400000)\n    return ok(17)\n",
        ),
        (
            "parent_permit_normal",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        (
            "parent_permit_cleanup_fault",
            "    await sleep(0)\n    return ok(17)\n",
        ),
        ("discard_value", "    return ok(17)\n"),
        ("discard_panic", panic_child),
        ("sibling_fault", panic_child),
        ("sibling_business_error", "    return fail(22)\n"),
    ] {
        let discards = mode.starts_with("parent_finish_")
            || mode.starts_with("parent_permit_")
            || mode.starts_with("discard_");
        let probes_sibling = mode.starts_with("sibling_");
        let task_import = if discards || probes_sibling {
            "from std.task import discard\n\n"
        } else {
            ""
        };
        let body = match mode {
            "body_error_before_await" | "sleep_body_error" => [body_error, receive].concat(),
            "body_error_after_await" => [receive, body_error].concat(),
            "body_assert_true" => ["        assert_true(True)\n", receive].concat(),
            "body_assert_false" | "sleep_body_panic" => {
                ["        assert_true(False)\n", receive].concat()
            }
            _ if discards => "        discard(handle)\n".to_owned(),
            "parent_wait_normal"
            | "parent_receive_pending"
            | "parent_receive_ready_cancel"
            | "parent_receive_value" => ["        await sleep(0)\n", receive].concat(),
            "parent_cancel" => ["        await sleep(86400000)\n", receive].concat(),
            _ => receive.to_owned(),
        };
        let (extra_child, extra_spawn, before_receive) = if probes_sibling {
            (
                if mode == "sibling_fault" {
                    "async def timer_child() -> Result[i64, i64]:\n    await sleep(86400000)\n    return ok(31)\n\n"
                } else {
                    "async def timer_child() -> Result[i64, i64]:\n    await sleep(0)\n    return ok(31)\n\n"
                },
                "        timer = spawn timer_child()\n",
                "        discard(timer)\n",
            )
        } else {
            ("", "", "")
        };
        let high_source = format!(
            r#"{task_import}{extra_child}async def child() -> Result[i64, i64]:
{child}
async def main() -> Result[unit, Error]:
    async with scope:
{extra_spawn}        handle = spawn child()
{before_receive}{body}    return ok(print("after scope"))
"#
        );
        let staging = probe_directory();
        let high_path = staging.path.join("program.nagi");
        fs::write(&high_path, &high_source).unwrap();
        let mut high = crate::source::load(&high_path, true).unwrap().program;
        check::check(&mut high).unwrap();
        let low = emit::low(&high);
        fs::remove_file(&high_path).unwrap();
        let low_path = staging.path.join("generated.low");
        fs::write(&low_path, &low).unwrap();
        let checked = check::finalize(
            crate::source::load(&low_path, false).unwrap().program,
            Default::default(),
            SourceProvenance::user_low_unmapped(),
        )
        .unwrap();
        let rejected = source(&checked, &[], BuildProfile::Dev).unwrap_err();
        assert!(
            rejected.contains("async task operations are not supported"),
            "{rejected}"
        );
        let probes_connection = mode == "parent_finish_connection";
        let generated = if probes_connection {
            super::task_lowering::source_with_connection(&checked)
        } else {
            super::task_lowering::source(&checked)
        }
        .unwrap();
        let connection_sources = [
            ("http.go", include_str!("http.go")),
            ("cors.go", include_str!("cors.go")),
            ("task_conn_probe.go", include_str!("task_conn_probe.go")),
        ];
        if probes_connection {
            for (name, content) in connection_sources {
                fs::write(staging.path.join(name), content).unwrap();
            }
        }
        let kernel = staging.path.join("internal/taskscope");
        fs::create_dir_all(&kernel).unwrap();
        fs::write(
            staging.path.join("go.mod"),
            include_str!("../../go-runtime/go.mod"),
        )
        .unwrap();
        fs::write(
            kernel.join("taskscope.go"),
            include_str!("../../go-runtime/internal/taskscope/taskscope.go"),
        )
        .unwrap();
        fs::write(staging.path.join("main.go"), generated).unwrap();
        let probes_panic = matches!(mode, "body_assert_false" | "sleep_body_panic");
        let probes_parent = mode.starts_with("parent_");
        if probes_parent || probes_panic || probes_sibling {
            fs::write(
                kernel.join("body_panic_probe.go"),
                include_str!("task_body_panic_probe.go"),
            )
            .unwrap();
        }
        let test_source = if probes_connection {
            include_str!("task_conn_probe_test.go")
        } else if probes_sibling {
            include_str!("task_sibling_fault_test.go")
        } else if probes_parent {
            include_str!("task_parent_cancel_test.go")
        } else if probes_panic {
            include_str!("task_body_panic_test.go")
        } else {
            include_str!("task_lowering_test.go")
        };
        fs::write(
            staging.path.join("lowering_test.go"),
            format!("{test_source}\nconst fixtureMode = {mode:?}\n"),
        )
        .unwrap();
        let repeats_permit = mode.starts_with("parent_permit_");
        if repeats_permit {
            fs::write(
                staging.path.join("permit_repetition_test.go"),
                include_str!("task_permit_repetition_test.go"),
            )
            .unwrap();
        }
        if let Some(root) = std::env::var_os("NAGI_TEST_ARTIFACT_DIR") {
            let path = PathBuf::from(root).join(mode);
            fs::create_dir_all(path.join("internal/taskscope")).unwrap();
            fs::write(path.join("program.nagi"), &high_source).unwrap();
            fs::write(path.join("generated.low"), low).unwrap();
            for file in [
                "go.mod",
                "main.go",
                "lowering_test.go",
                "internal/taskscope/taskscope.go",
            ] {
                fs::copy(staging.path.join(file), path.join(file)).unwrap();
            }
            if probes_parent || probes_panic || probes_sibling {
                let file = "internal/taskscope/body_panic_probe.go";
                fs::copy(staging.path.join(file), path.join(file)).unwrap();
            }
            if probes_connection {
                for (file, _) in connection_sources {
                    fs::copy(staging.path.join(file), path.join(file)).unwrap();
                }
            }
            if repeats_permit {
                let file = "permit_repetition_test.go";
                fs::copy(staging.path.join(file), path.join(file)).unwrap();
            }
        }
        let output = go_output(
            &["test", "-count=1", "-timeout=20s", "-v", "."],
            &staging.path,
        )
        .unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(output.status.success(), "{mode}\n{stdout}\n{stderr}");
        assert!(
            stdout.contains("--- PASS: TestCheckedTaskLowering "),
            "{mode}: {stdout}"
        );
        if repeats_permit {
            assert!(
                stdout.contains("--- PASS: TestParentPermitRepetition "),
                "{mode}: {stdout}"
            );
        }
        assert_eq!(
            stdout.lines().any(|line| line == "after scope"),
            matches!(
                mode,
                "value"
                    | "business_error"
                    | "discard_value"
                    | "body_assert_true"
                    | "sleep_value"
                    | "sleep_business_error"
                    | "parent_wait_normal"
                    | "parent_receive_value"
                    | "parent_finish_normal"
                    | "parent_permit_normal"
                    | "sibling_business_error"
            ),
            "{stdout}"
        );
        println!("{mode}\n{stdout}");
    }
}
